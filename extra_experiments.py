"""
Remaining numerical experiments of Section 6 of the paper (journal version):

  --table1      Table 1: dependence on the number of time steps Nt and modes M
                (alpha = 0.75, f(s) = sin s)
  --fine        errors for eps = 1e-10 with Nt = 1600, M = 120 for all orders
                (quoted in the text of Section 6.2)
  --table2      Table 2: f(s) = a s + sin s, a in {0, 3, 12}, alpha = 0.75
  --fig4        Figure 4: error, cost and terminal states for f(s) = a s + sin s
  --generator   comparison of the generators A and A_a for u = 0, a = 12
                (Section 6.3; illustrates Lemma 5.4)

Without arguments all experiments are run. Figures 1-3 are produced by
subdiffusion_control.py.
"""
import argparse
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from subdiffusion_control import Problem

T = 1.0
OMEGA = (0.2, 0.4)
y0 = lambda x: np.sin(np.pi * x)
y1 = lambda x: np.exp(-30 * (x - 0.7) ** 2)


def data(P):
    return P.to_modes(y0(P.x)), P.to_modes(y1(P.x))


# ----------------------------------------------------------------------
def table1():
    """Table 1 (alpha = 0.75, f = sin, theta = 0.5)."""
    grids = [(400, 60), (800, 60), (400, 120), (800, 120), (1600, 120)]
    epss = [1e-2, 1e-6, 1e-10]
    lines = []
    for Nt, M in grids:
        P = Problem(0.75, T, Nt, M, omega=OMEGA)
        a0, a1 = data(P)
        row = [str(Nt), str(M)]
        for eps in epss:
            r = P.control(a0, a1, eps)
            row += [f"{r['err']:.2e}", f"{r['cost']:.2e}"]
        lines.append(" & ".join(row) + r" \\")
        print("Table 1:", "  ".join(row), flush=True)
    with open("table_convergence.tex", "w") as fh:
        fh.write("% generated by extra_experiments.py --table1\n")
        fh.write("% Nt & M & (error, cost) for eps = 1e-2, 1e-6, 1e-10\n")
        fh.write("\n".join(lines) + "\n")


def fine():
    """Errors for eps = 1e-10 on the finest grid, all orders."""
    for alpha in [0.6, 0.75, 0.9]:
        P = Problem(alpha, T, 1600, 120, omega=OMEGA)
        a0, a1 = data(P)
        r = P.control(a0, a1, 1e-10)
        print(f"Nt=1600, M=120, alpha={alpha}: |y(T)-y1| = {r['err']:.2e}", flush=True)


# ----------------------------------------------------------------------
A_VALUES = [0.0, 3.0, 12.0]
EXPS = np.arange(1, 11)
EPSS = 10.0 ** -EXPS


def unbounded_runs():
    """f(s) = a s + sin s with the linear part in the generator, theta = 0.2."""
    runs = {}
    for a in A_VALUES:
        P = Problem(0.75, T, 400, 60, omega=OMEGA, a=a)
        a0, a1 = data(P)
        res = []
        for eps in EPSS:
            r = P.control(a0, a1, eps, theta=0.2)
            res.append(r)
            print(f"a={a:4.1f} eps={eps:7.1e}  |y(T)-y1|={r['err']:9.3e}"
                  f"  |u|={r['cost']:9.3e}  it={r['it']:3d}  identity={r['ident']:.1e}",
                  flush=True)
        runs[a] = (P, a0, a1, res)
    return runs


def table2(runs):
    with open("table_unbounded.tex", "w") as fh:
        fh.write("% generated by extra_experiments.py --table2\n")
        fh.write("% eps & (error, cost) for a = 0, 3, 12; alpha = 0.75\n")
        for k, eps in enumerate(EPSS):
            if EXPS[k] % 2:
                continue
            row = [f"$10^{{-{EXPS[k]}}}$"]
            for a in A_VALUES:
                r = runs[a][3][k]
                row += [f"{r['err']:.2e}", f"{r['cost']:.2e}"]
            fh.write(" & ".join(row) + r" \\" + "\n")


def fig4(runs):
    fig, ax = plt.subplots(1, 3, figsize=(14, 4))
    for a in A_VALUES:
        P, a0, a1, res = runs[a]
        lab = rf"$a={a:g}$, $\lambda_1^a={P.lam[0]:.2f}$"
        ax[0].loglog(EPSS, [r["err"] for r in res], "o-", label=lab)
        ax[1].loglog(EPSS, [r["cost"] for r in res], "o-", label=lab)
    ax[0].set_ylabel(r"$\|y_\varepsilon(T)-y_1\|$")
    ax[1].set_ylabel(r"$\|u_\varepsilon\|_{L^2(\omega\times(0,T))}$")
    for a_ in ax[:2]:
        a_.set_xlabel(r"$\varepsilon$")
        a_.grid(True, which="both", alpha=0.3)
        a_.legend(fontsize=8)
        a_.invert_xaxis()

    # terminal states for a = 12
    P, a0, a1, res = runs[12.0]
    yu = P.to_phys(P.forward(a0, np.zeros_like(res[0]["U"]))[0][-1])  # u = 0
    scale = np.abs(yu).max()
    ax[2].plot(P.x, P.to_phys(a1), "k--", lw=2, label=r"target $y_1$")
    for k in [1, 5, 9]:
        ax[2].plot(P.x, P.to_phys(res[k]["a"][-1]),
                   label=rf"$y_\varepsilon(T)$, $\varepsilon=10^{{-{EXPS[k]}}}$")
    ax[2].plot(P.x, yu / scale, ":", label=rf"uncontrolled $y(T)$, scaled by 1/{scale:.1f}")
    ax[2].axvspan(*OMEGA, color="grey", alpha=0.2, label=r"$\omega$")
    ax[2].set_title(r"$a=12$")
    ax[2].set_xlabel("$x$")
    ax[2].legend(fontsize=7)
    ax[2].grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig("fig_unbounded.pdf")
    fig.savefig("fig_unbounded.png", dpi=150)


# ----------------------------------------------------------------------
def generator():
    """u = 0, a = 12: generator A with f(s) = 12 s + sin s (explicit) versus
    generator A_a with h(s) = sin s. The difference of the terminal states
    should be roughly halved at each refinement (first-order error of the
    explicit treatment of the linear term)."""
    lines = ["Nt    |y_A(T) - y_Aa(T)|    |y_Aa(T)|"]
    for Nt in [100, 200, 400, 800, 1600]:
        PA = Problem(0.75, T, Nt, 60, omega=OMEGA, f=lambda s: 12 * s + np.sin(s))
        Pa = Problem(0.75, T, Nt, 60, omega=OMEGA, a=12.0)
        a0 = PA.to_modes(y0(PA.x))
        U = np.zeros((Nt, PA.x.size))
        yA = PA.forward(a0, U)[0][-1]
        ya = Pa.forward(a0, U)[0][-1]
        lines.append(f"{Nt:<5d} {np.linalg.norm(yA - ya):12.2f} {np.linalg.norm(ya):17.2f}")
    lines.append(f"|y0| = {np.linalg.norm(a0):.2f}")
    print("\n".join(lines), flush=True)
    with open("generator_check.txt", "w") as fh:
        fh.write("\n".join(lines) + "\n")


# ----------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    for name in ["table1", "fine", "table2", "fig4", "generator"]:
        ap.add_argument(f"--{name}", action="store_true")
    args = ap.parse_args()
    run_all = not any(vars(args).values())

    if run_all or args.table1:
        table1()
    if run_all or args.fine:
        fine()
    if run_all or args.table2 or args.fig4:
        runs = unbounded_runs()
        if run_all or args.table2:
            table2(runs)
        if run_all or args.fig4:
            fig4(runs)
    if run_all or args.generator:
        generator()


if __name__ == "__main__":
    main()
